"""Generate the texmf-dist melange recipe from a TeX Live release.

TeX Live describes itself in texlive.tlpdb: every package with its run,
source and doc files, and every collection with the packages and other
collections it depends on. Alpine's texmf-dist APKBUILD splits the texmf
tarball by collection at build time with a set of shell functions; melange
recipes are static, so this writes one subpackage per collection (plus its
-doc), with the dependencies between collections taken from the tlpdb.

Usage:
    texlive-to-melange.py --release 20260301 --tlpdb texlive.tlpdb \\
        --texmf-sha512 <sha512 of texlive-RELEASE-texmf.tar.xz> \\
        --extra-sha512 <sha512 of texlive-RELEASE-extra.tar.xz> \\
        --out packages/texmf-dist.yaml
"""

import argparse
import re
import sys

HISTORIC = "https://ftp.tu-chemnitz.de/pub/tug/historic/systems/texlive"

# Windows-only collections; basic is the main package
SKIP = {"basic", "texworks", "wintools"}

HEADER = """\
# SPDX-License-Identifier: GPL-3.0-or-later
# SPDX-FileCopyrightText: 2026 Juan Manuel Méndez Rey <vejeta@gmail.com>
#
# Generated by tools/texlive-to-melange from the TeX Live {year} tlpdb
# (release {release}). Do not edit: regenerate.
#
# The texmf tree of TeX Live, split by collection as Alpine's texmf-dist
# does: texmf-dist is collection-basic, texmf-dist-<collection> each other
# collection, with its documentation in texmf-dist-<collection>-doc.
# The TeX programs are in the texlive package.
"""


def parse_tlpdb(path):
    """{package name: {"depend": [...], "shortdesc": str, "run": [...], "src": [...], "doc": [...]}}"""
    db, cur, files = {}, None, None
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line:
                cur, files = None, None
                continue
            if line.startswith("name "):
                cur = db.setdefault(line[5:], {"depend": [], "shortdesc": "", "run": [], "src": [], "doc": []})
                continue
            if cur is None:
                continue
            m = re.match(r"^(run|src|doc|bin)files ", line)
            if m:
                files = m.group(1) if m.group(1) != "bin" else None
                continue
            if line.startswith(" "):
                if files:
                    cur[files].append(line.split()[0])
                continue
            files = None
            if line.startswith("depend "):
                cur["depend"].append(line[7:])
            elif line.startswith("shortdesc "):
                cur["shortdesc"] = line[10:]
    return db


def quote(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--release", required=True, help="release date, e.g. 20260301")
    ap.add_argument("--tlpdb", required=True)
    ap.add_argument("--texmf-sha512", required=True)
    ap.add_argument("--extra-sha512", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    year = a.release[:4]
    db = parse_tlpdb(a.tlpdb)
    collections = sorted(n[len("collection-"):] for n in db if n.startswith("collection-"))
    wanted = [c for c in collections if c not in SKIP]
    if "basic" not in collections:
        sys.exit("error: no collection-basic in " + a.tlpdb)

    out = [HEADER.format(year=year, release=a.release)]
    out.append("""package:
  name: texmf-dist
  version: '{year}.0'
  epoch: 0
  description: TeX Live texmf tree, basic collection
  copyright:
    - license: GPL-2.0-or-later AND LPPL-1.3c AND OFL-1.1 AND GPL-3.0-or-later AND LicenseRef-TeX-Live
  dependencies:
    runtime:
      - perl
  scriptlets:
    trigger:
      paths:
        - /usr/share/texmf-dist/tex/generic/config/lang.d
      script: |
        #!/bin/sh
        # the hyphenation configuration is assembled from the collections installed
        d=/usr/share/texmf-dist/tex/generic/config
        for ext in def dat dat.lua; do
          cat $(find $d/lang.d -name "*.$ext" | sort) > $d/language.$ext 2>/dev/null || true
        done
environment:
  contents:
    keyring:
      - https://packages.wolfi.dev/os/wolfi-signing.rsa.pub
    repositories:
      - https://packages.wolfi.dev/os
    packages:
      - busybox
      - patch
      - xz
pipeline:
  - name: Move the recipe files out of the build tree
    runs: |
      mkdir -p .recipe-files
      mv texmf-dist/* .recipe-files/
      rmdir texmf-dist
      mkdir extra  # where the second fetch extracts
  - uses: fetch
    with:
      uri: {historic}/{year}/texlive-${{{{vars.release}}}}-texmf.tar.xz
      expected-sha512: {texmf}
  - uses: fetch
    with:
      uri: {historic}/{year}/texlive-${{{{vars.release}}}}-extra.tar.xz
      expected-sha512: {extra}
      directory: extra
  - name: Prepare
    runs: |
      cp extra/tlpkg/texlive.tlpdb texlive-${{{{package.version}}}}.tlpdb
      for p in .recipe-files/*.patch; do patch -p1 < "$p"; done
      # the scripts the tlpdb lists are executable
      find texmf-dist -type f \\( -name '*.sh' -o -name '*.py' -o -name '*.lua' -o -name '*.perl' \\) | while read -r f; do
        head -n 1 "$f" | grep -Eq '^#!/(usr/)?bin' && chmod +x "$f" || true
      done
      cat > .recipe-files/pack.sh <<'EOF'
      #!/bin/sh
      # pack.sh COLLECTION DATADIR DOCDIR: move the files of a collection's packages
      tlpdb=texlive-${{{{package.version}}}}.tlpdb
      c="$1" data="$2" doc="$3"
      awk -v want="collection-$c" '
        /^name / {{ name = substr($0, 6); next }}
        name == want && /^depend / {{ d = substr($0, 8); if (d !~ /^collection-/) print d }}
      ' "$tlpdb" > deps.$c
      awk -v list=deps.$c '
        BEGIN {{ while ((getline l < list) > 0) want[l] = 1 }}
        /^name / {{ name = substr($0, 6); kind = ""; next }}
        /^(run|src)files / {{ kind = "data"; next }}
        /^docfiles / {{ kind = "doc"; next }}
        /^[a-z]/ {{ kind = ""; next }}
        /^ texmf-dist\\// && kind != "" && (name in want) {{ print kind, $1 }}
      ' "$tlpdb" | while read -r kind path; do
        [ -e "$path" ] || continue
        if [ "$kind" = data ]; then dest="$data"; else dest="$doc"; fi
        mkdir -p "$dest/usr/share/$(dirname "$path")"
        mv "$path" "$dest/usr/share/$path"
      done
      EOF
      chmod +x .recipe-files/pack.sh
  - name: Basic collection
    runs: |
      .recipe-files/pack.sh basic "${{{{targets.destdir}}}}" "${{{{targets.outdir}}}}/texmf-dist-doc"
      # the Perl modules of tlmgr and updmap
      mkdir -p "${{{{targets.destdir}}}}"/usr/share/tlpkg
      cp -a extra/tlpkg/TeXLive "${{{{targets.destdir}}}}"/usr/share/tlpkg/
      cfg="${{{{targets.destdir}}}}"/usr/share/texmf-dist/tex/generic/config
      mkdir -p "$cfg/lang.d"
      for ext in def dat dat.lua; do
        rm -f "$cfg/language.$ext"
        cp .recipe-files/00-preamble.$ext .recipe-files/90-epilog.$ext "$cfg/lang.d/"
      done
      install -Dm644 extra/LICENSE.TL -t "${{{{targets.destdir}}}}"/usr/share/licenses/texmf-dist
      install -Dm644 extra/LICENSE.CTAN -t "${{{{targets.destdir}}}}"/usr/share/licenses/texmf-dist
vars:
  release: '{release}'
subpackages:
  - name: texmf-dist-doc
    description: TeX Live texmf tree, basic collection (documentation)
    pipeline:
      - runs: |
          mkdir -p "${{{{targets.contextdir}}}}"
""".format(year=year, release=a.release, historic=HISTORIC, texmf=a.texmf_sha512, extra=a.extra_sha512))

    for c in wanted:
        info = db["collection-" + c]
        deps = ["texmf-dist"] + ["texmf-dist-" + d[len("collection-"):] for d in info["depend"]
                                 if d.startswith("collection-") and d[len("collection-"):] in wanted]
        lang = ""
        if c.startswith("lang"):
            lang = """
          cfg="${{{{targets.contextdir}}}}"/usr/share/texmf-dist/tex/generic/config/lang.d
          mkdir -p "$cfg"
          for ext in def dat dat.lua; do
            [ -e .recipe-files/10-{c}.$ext ] && cp .recipe-files/10-{c}.$ext "$cfg/"
          done""".format(c=c)
        provides = ""
        if c == "bibtexextra":
            # biblatex, which Alpine and Debian package on its own, is in this collection
            provides = "\n      provides:\n        - biblatex=${{package.full-version}}"
        out.append("""  - name: texmf-dist-{c}
    description: {desc}
    dependencies:{provides}
      runtime:
{deps}
    pipeline:
      - runs: |
          .recipe-files/pack.sh {c} "${{{{targets.contextdir}}}}" "${{{{targets.outdir}}}}/texmf-dist-{c}-doc"{lang}
          mkdir -p "${{{{targets.contextdir}}}}"
  - name: texmf-dist-{c}-doc
    description: {docdesc}
    pipeline:
      - runs: |
          mkdir -p "${{{{targets.contextdir}}}}"
""".format(c=c, desc=quote("TeX Live: " + (info["shortdesc"] or c)),
           docdesc=quote("TeX Live: " + (info["shortdesc"] or c) + " (documentation)"),
           deps="\n".join("        - " + d for d in deps), lang=lang, provides=provides))

    # meta packages, as Alpine has them
    lang = [c for c in wanted if c.startswith("lang")]
    most = [c for c in wanted if not c.startswith("lang") and c != "fontsextra"]
    for meta, desc, deps in (
            ("lang", "TeX Live texmf tree: additional languages", ["texmf-dist-" + c for c in lang]),
            ("most", "TeX Live texmf tree with most collections (not the languages or fontsextra)",
             ["texmf-dist-" + c for c in most]),
            ("full", "Full TeX Live texmf tree", ["texmf-dist-most", "texmf-dist-lang", "texmf-dist-fontsextra"])):
        out.append("""  - name: texmf-dist-{m}
    description: {d}
    dependencies:
      runtime:
{deps}
    pipeline:
      - runs: |
          mkdir -p "${{{{targets.contextdir}}}}"
""".format(m=meta, d=quote(desc), deps="\n".join("        - " + x for x in ["texmf-dist"] + deps)))

    out.append("""update:
  enabled: false
  manual: true
  exclude-reason: TeX Live publishes one release a year; regenerate with tools/texlive-to-melange
test:
  environment:
    contents:
      packages:
        - busybox
  pipeline:
    - runs: |
        test -f /usr/share/texmf-dist/web2c/texmf.cnf
        grep -q '^TEXMFROOT = /usr/share' /usr/share/texmf-dist/web2c/texmf.cnf
        test -f /usr/share/tlpkg/TeXLive/TLPDB.pm
""")
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write("".join(out))
    print("wrote {} ({} collections)".format(a.out, len(wanted)), file=sys.stderr)


if __name__ == "__main__":
    main()
