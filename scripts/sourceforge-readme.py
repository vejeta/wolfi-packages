"""Write the README.md of the SourceForge files area from the repository's README.

SourceForge shows the README.md at the top of https://sourceforge.net/projects/wolfi/files/.
The publish workflow writes it into the repository directory it syncs, so it follows
the README of the repository instead of being kept by hand:

    scripts/sourceforge-readme.py --out repo/README.md
    scripts/sourceforge-readme.py --stdout

Relative links become links to GitHub; sections for contributors (Contributing,
Tools) point to GitHub instead of being copied.
"""

import argparse
import datetime
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GITHUB = "https://github.com/vejeta/wolfi-packages"

# sections of README.md for people who change the repository: a link is enough
LINKED = {"Contributing": "#contributing", "Tools": "#tools"}


def absolute_links(text, branch="master"):
    """[x](PACKAGES.md), [x](packages/) and [x](#anchor) -> links to the GitHub repository."""
    def repl(m):
        label, target = m.group(1), m.group(2)
        if re.match(r"^[a-z]+:|^//", target):
            return m.group(0)
        if target.startswith("#"):
            return "[{}]({}{})".format(label, GITHUB, target)
        path = target.split("#")[0]
        kind = "tree" if path.endswith("/") or os.path.isdir(os.path.join(ROOT, path)) else "blob"
        return "[{}]({}/{}/{}/{})".format(label, GITHUB, kind, branch, target)
    # the label may be an image: [![badge](https://img...)](PACKAGES.md)
    return re.sub(r"(?<!!)\[((?:!\[[^\]]*\]\([^)]*\)|[^\]])*)\]\(([^)\s]+)\)", repl, text)


def sections(text):
    """[(title or None for the preamble, body)] split at the level-2 headings."""
    out, title, body = [], None, []
    for line in text.splitlines(keepends=True):
        m = re.match(r"^## (.+?)\s*$", line)
        if m:
            out.append((title, "".join(body)))
            title, body = m.group(1), []
        body.append(line)
    out.append((title, "".join(body)))
    return out


def render(readme, date):
    parts = []
    for title, body in sections(readme):
        if title in LINKED:
            parts.append("## {}\n\nSee [{}]({}{}) on GitHub.\n\n".format(title, title, GITHUB, LINKED[title]))
        else:
            parts.append(body)
    text = absolute_links("".join(parts)).rstrip("\n")
    return ("<!-- Generated by scripts/sourceforge-readme.py from the README of {}. Do not edit here. -->\n"
            "{}\n\n---\n\nThis page follows the [README on GitHub]({}#readme); last updated {}.\n").format(
                GITHUB, text, GITHUB, date)


def last_change(path):
    """The date of the last commit (UTC), or today when git cannot tell."""
    try:
        out = subprocess.run(["git", "-C", ROOT, "log", "-1", "--format=%cs", "--", path],
                             capture_output=True, text=True, check=True).stdout.strip()
        if out:
            return out
    except (OSError, subprocess.CalledProcessError):
        pass
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--readme", default=os.path.join(ROOT, "README.md"))
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--out", help="file to write (the README.md of the synced directory)")
    g.add_argument("--stdout", action="store_true")
    a = p.parse_args(argv)
    with open(a.readme, encoding="utf-8") as fh:
        text = render(fh.read(), last_change(a.readme))
    if a.stdout:
        sys.stdout.write(text)
        return 0
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote {}".format(a.out), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
