"""Tests for scripts/sourceforge-readme.py."""

import importlib.util
import os
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("sf_readme", os.path.join(HERE, "sourceforge-readme.py"))
sf = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sf)

README = """\
# Title

[![Packages](https://img.shields.io/badge/packages-3-brightgreen)](PACKAGES.md)

Intro with [the recipes](packages/) and [usage](#using-these-packages).

## Using these packages

```
Repository: https://downloads.sourceforge.net/project/wolfi
```

## Contributing

Long contributor guide.

## License

[GPL-3.0-or-later](LICENSE), see ![logo](img.png).
"""


class SourceForgeReadmeTest(unittest.TestCase):

    def setUp(self):
        self.text = sf.render(README, "2026-10-20")

    def test_relative_links_point_to_github(self):
        self.assertIn("](https://github.com/vejeta/wolfi-packages/blob/master/PACKAGES.md)", self.text)
        self.assertIn("[the recipes](https://github.com/vejeta/wolfi-packages/tree/master/packages/)", self.text)
        self.assertIn("[usage](https://github.com/vejeta/wolfi-packages#using-these-packages)", self.text)
        self.assertIn("[GPL-3.0-or-later](https://github.com/vejeta/wolfi-packages/blob/master/LICENSE)", self.text)
        # absolute links and images are left alone
        self.assertIn("(https://img.shields.io/badge/packages-3-brightgreen)", self.text)
        self.assertIn("![logo](img.png)", self.text)

    def test_contributor_sections_link_to_github(self):
        self.assertNotIn("Long contributor guide", self.text)
        self.assertIn("See [Contributing](https://github.com/vejeta/wolfi-packages#contributing) on GitHub.", self.text)
        self.assertIn("Repository: https://downloads.sourceforge.net/project/wolfi", self.text)

    def test_generated_header_and_date(self):
        self.assertTrue(self.text.startswith("<!-- Generated by scripts/sourceforge-readme.py"))
        self.assertIn("last updated 2026-10-20.", self.text)

    def test_repository_readme_renders(self):
        with open(os.path.join(sf.ROOT, "README.md"), encoding="utf-8") as fh:
            text = sf.render(fh.read(), "2026-10-20")
        self.assertIn("https://wolfi.vejeta.com", text)
        self.assertNotRegex(text, r"\]\((?!https?:|#|mailto:)[^)]+\.md\)")


if __name__ == "__main__":
    unittest.main()
