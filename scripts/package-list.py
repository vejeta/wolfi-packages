"""Write PACKAGES.md, the list of the recipes in packages/.

One row per recipe: name, version, description, license and the number of
subpackages, in name order. The README links to the file and shows the
count; run this after adding or removing recipes:

    scripts/package-list.py            # writes PACKAGES.md
    scripts/package-list.py --check    # exit 1 if PACKAGES.md is out of date
"""

import argparse
import glob
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

HEADER = """\
<!-- Generated by scripts/package-list.py from packages/*.yaml. Do not edit. -->
# Packages

{count} recipes in [`packages/`](packages/), with {subs} subpackages. The
recipe is the reference for each version; [README](README.md#available-packages)
groups them by area.

| Package | Version | Description | License | Subpackages |
|---------|---------|-------------|---------|-------------|
"""


def cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def recipes(directory):
    rows = []
    for path in sorted(glob.glob(os.path.join(directory, "*.yaml"))):
        with open(path, encoding="utf-8") as fh:
            data = yaml.load(fh, Loader=yaml.BaseLoader) or {}
        pkg = data.get("package") or {}
        if not pkg.get("name"):
            continue
        lic = " AND ".join(c.get("license", "") for c in pkg.get("copyright") or [] if c.get("license"))
        subs = data.get("subpackages") or []
        ranges = {d.get("name"): d.get("items") or {} for d in data.get("data") or []}
        n = sum(len(ranges.get(s.get("range"), {})) if s.get("range") else 1 for s in subs)
        rows.append((pkg["name"], pkg.get("version", ""), pkg.get("description", ""), lic, n))
    return rows


def render(rows):
    out = HEADER.format(count=len(rows), subs=sum(r[4] for r in rows))
    for name, version, desc, lic, n in sorted(rows, key=lambda r: r[0].lower()):
        out += "| [{0}](packages/{0}.yaml) | {1} | {2} | {3} | {4} |\n".format(
            name, cell(version), cell(desc), cell(lic), n)
    return out


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--packages-dir", default=os.path.join(ROOT, "packages"))
    p.add_argument("--out", default=os.path.join(ROOT, "PACKAGES.md"))
    p.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    a = p.parse_args(argv)
    text = render(recipes(a.packages_dir))
    if a.check:
        try:
            with open(a.out, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = ""
        if current != text:
            print("{} is out of date: run scripts/package-list.py".format(a.out), file=sys.stderr)
            return 1
        return 0
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote {}".format(a.out), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
